pub fn create_jmp1(addr: u64) -> Result<Vec<u8>> {
    let mut encoder = Encoder::new(64);

    let mut new_ins1 = Instruction::with2(Code::Mov_r64_imm64, Register::RAX, addr as u64)?;
    let len = get_ins_len(&new_ins1)?;
    new_ins1.set_len(len);

    let mut new_ins2 = Instruction::with1(Code::Jmp_rm64, Register::RAX)?;
    let len = get_ins_len(&new_ins2)?;
    new_ins2.set_len(len);

    encoder.encode(&new_ins1, addr)?;
    encoder.encode(&new_ins2, addr + new_ins1.len() as u64)?;

    Ok(encoder.take_buffer())
}

pub fn get_ins_len(ins: &Instruction) -> Result<usize> {
    let mut encoder = Encoder::new(64);
    Ok(encoder.encode(ins, ins.ip())?)
}
